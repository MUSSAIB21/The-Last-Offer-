_http_client = None

def _get_client():
    global _http_client
    if _http_client is None or _http_client.is_closed:
        _http_client = httpx.AsyncClient(timeout=30.0)
    return _http_client

async def groq_call(messages, max_tokens=280, temperature=0.7, model=None):
    """Single Groq call with one automatic retry on transient failure."""
    use_model = model or MODEL
    client = _get_client()
    for attempt in range(2):
        try:
            r = await client.post(
                'https://api.groq.com/openai/v1/chat/completions',
                headers={'Authorization': f'Bearer {GROQ_API_KEY}', 'Content-Type': 'application/json'},
                json={'model': use_model, 'messages': messages, 'temperature': temperature, 'max_tokens': max_tokens}
            )
            if r.status_code == 200:
                return r.json()['choices'][0]['message']['content']
            if r.status_code == 429 and attempt == 0:
                retry_after = r.headers.get('retry-after')
                wait = min(float(retry_after), 8) if retry_after else 4
                await asyncio.sleep(wait)
                continue
            raise Exception(f'HTTP {r.status_code}')
        except (httpx.TimeoutException, httpx.ConnectError) as e:
            if attempt == 0:
                await asyncio.sleep(2)
                continue
            raise Exception(f'Connection failed after retry: {e}')
    raise Exception('Groq call failed after 2 attempts')

def extract(text, label):
    m = re.search(rf'{label}:\s*(.+?)(?=\n(?:QUESTION|FOLLOW-UP|VERDICT|REASON):|$)', text, re.DOTALL | re.IGNORECASE)
    return m.group(1).strip() if m else text.strip()


def strip_hedges(reason):
    """Remove softening language from verdict reasons."""
    LEAD = re.compile(
        r'^(?:while|although|even though|despite|that said|however|to be fair|'
        r'i can see the potential|there is potential|this has potential|'
        r'interesting idea|good concept|i like the concept)'
        r'[^,.!?]*[,.] *',
        re.IGNORECASE
    )
    TAIL = re.compile(
        r',?[ ]?(?:but[ ]+)?(?:good luck|best of luck|keep iterating|'
        r'worth revisiting|come back when|happy to revisit|'
        r'not a no forever|not a permanent pass|'
        r'feel free to reach out)[^.]*\.?$',
        re.IGNORECASE
    )
    reason = LEAD.sub('', reason).strip()
    reason = TAIL.sub('', reason).strip()
    if reason:
        reason = reason[0].upper() + reason[1:]
    if reason and reason[-1] not in '.!?':
        reason += '.'
    return reason

async def validate_pitch(pitch):
    """
    Returns (is_valid: bool, feedback: str).
    Checks for the four things investors need to ask real questions:
    what it does, who it's for, how it makes money, why now.
    One Groq call. Fast model, low token cost.
    """
    msgs = [
        {'role': 'system', 'content': """You are a pitch screener. Your only job is to catch pitches so vague that no investor could form a question.

The bar is LOW. You are checking for the minimum, not quality.

VALID = YES if the pitch contains at least: a description of what the product does (even roughly).
Everything else — who the customer is, how it makes money, why now — can be vague or missing. Investors will surface those gaps themselves.

VALID = NO only if: the pitch is a single sentence with no product description, or so abstract it could mean anything ("I have an app idea", "a platform for people", "disrupting an industry").

You need to find:
1. WHAT — what the product does. Even "contract review software" is enough. Fail only if completely absent or meaningless.
2. WHO — target customer. Optional — only flag if genuinely absent AND WHAT is also weak.
3. MONEY — monetisation. Always optional. Never fail on this alone.
4. WHY — timing/context. Always optional. Never fail on this alone.

Respond with ONLY this format:
VALID: YES or NO
MISSING: comma-separated list using labels WHAT / WHO / MONEY / WHY (or NONE)
FEEDBACK: one sentence on what would make this a stronger pitch (not a rejection reason)

When in doubt, return VALID: YES."""},
        {'role': 'user', 'content': f"Pitch: {pitch}"}
    ]
    try:
        resp  = await groq_call(msgs, max_tokens=120, model=LIGHT_MODEL)
        valid = bool(re.search(r'VALID:\s*YES', resp, re.IGNORECASE))
        fb_m  = re.search(r'FEEDBACK:\s*(.+)', resp, re.IGNORECASE)
        miss_m = re.search(r'MISSING:\s*(.+)', resp, re.IGNORECASE)
        missing  = miss_m.group(1).strip() if miss_m else ''
        feedback = fb_m.group(1).strip()   if fb_m  else ''
        return valid, missing, feedback
    except Exception:
        # If validation itself fails, let the pitch through rather than blocking the game
        return True, '', ''


async def extract_claims(investor_name, q1, a1, q2, a2):
    """
    After each round, lift specific factual claims from the founder's answers.
    One small Groq call. Quotes directly — no paraphrasing.
    Returns a formatted string block or empty string if no claims found.
    """
    prompt = (
        f"The following are a founder's answers during a pitch meeting with {investor_name}.\n\n"
        f"Answer 1 (to: {q1}):\n{a1}\n\n"
        f"Answer 2 (to: {q2}):\n{a2}\n\n"
        "Extract only the specific factual claims — numbers, named customers, "
        "stated timelines, explicit commitments, named technologies. "
        "Return as a short bullet list. Quote the founder's exact words where possible. "
        "If there are no specific claims, return the single word NONE."
    )
    try:
        resp = await groq_call(
            [{'role': 'user', 'content': prompt}],
            max_tokens=200,
            temperature=0.0,
            model=LIGHT_MODEL
        )
        resp = resp.strip()
        if resp.upper() == 'NONE' or not resp:
            return ''
        return f"To {investor_name}:\n{resp}"
    except Exception:
        return ''


