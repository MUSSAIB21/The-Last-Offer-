def extract_ask(founder_text):
    """
    Detect if the founder just stated their investment ask.
    Pure regex — no API call.
    Returns dict: {found, amount, equity, valuation, partial}
    """
    text = founder_text
    lower = founder_text.lower()
    amount = None
    equity = None
    valuation = None

    fundraising_context = re.search(
        r'\b(?:raising|raise|fundraising|funding|seeking|looking for|asking for|'
        r'our ask|the ask|investment|invest|round|capital|in exchange for|equity)\b',
        lower,
        re.IGNORECASE
    )

    # Amount patterns: £200k, $1m, 500k, £2 million, etc.
    amt_m = re.search(
        r'([£$€]?\s*[\d,.]+\s*(?:k|m|million|thousand|hundred thousand|billion)\b)',
        text, re.IGNORECASE
    )
    if amt_m:
        amount = amt_m.group(1).strip()

    # Equity patterns: 10%, 10 percent, ten percent
    eq_m = re.search(r'(\d+(?:\.\d+)?)\s*(?:%|percent)', text, re.IGNORECASE)
    if eq_m:
        equity = eq_m.group(1) + '%'

    # Valuation patterns: "valued at £2m", "valuation of $10m", "worth £5 million"
    val_m = re.search(
        r'(?:valu(?:ed?|ation)\s+(?:at|of|is)|worth)\s*([£$€]?\s*[\d,.]+\s*(?:k|m|million|billion)\b)',
        text, re.IGNORECASE
    )
    if val_m:
        valuation = val_m.group(1).strip()

    paired_terms = re.search(
        r'([£$€]?\s*[\d,.]+\s*(?:k|m|million|thousand|hundred thousand|billion)\b)'
        r'[^.\n]{0,40}?'
        r'(?:for|in exchange for)\s*'
        r'(\d+(?:\.\d+)?)\s*(?:%|percent)',
        text, re.IGNORECASE
    )

    if not (amount or equity or valuation):
        return {'found': False}

    # Product pricing and operational numbers should not be mistaken for a funding ask.
    if not fundraising_context and not paired_terms:
        return {'found': False}

    partial = not (amount and equity)
    return {'found': True, 'amount': amount, 'equity': equity,
            'valuation': valuation, 'partial': partial}


async def extract_deal_action(inv_name, inv_title, founder_text, state):
    """
    Detect if the founder just accepted, rejected, or countered an offer.
    Uses the 8b model (14,400 req/day) for nuanced intent detection.
    Returns dict: {action: accept|reject|counter|none, counter_amount, counter_equity}
    """
    open_offers = {k: v for k, v in state['offers'].items() if v.get('status') == 'open'}
    if not open_offers:
        return {'action': 'none'}

    offer_summary = ', '.join(
        f"{name}: {o.get('raw', '?')}" for name, o in open_offers.items()
    )
    prompt = (
        f"Open offers on the table: {offer_summary}\n"
        f"The founder just said: \"{founder_text}\"\n\n"
        "What is the founder doing? Reply with exactly one line:\n"
        "ACCEPT <investor name> — if they are accepting an offer\n"
        "REJECT <investor name> — if they are turning down an offer\n"
        "COUNTER <investor name> <amount> <equity> — if they are proposing different terms\n"
        "NONE — if they are not responding to any offer\n\n"
        "Reply with a single line."
    )
    try:
        resp = await groq_call(
            [{'role': 'user', 'content': prompt}],
            max_tokens=30, temperature=0, model=LIGHT_MODEL
        )
        line = resp.strip().upper()
        # Parse ACCEPT
        m = re.match(r'ACCEPT\s+(.*)', line, re.IGNORECASE)
        if m:
            name_hint = m.group(1).strip()
            target = state.get('active_deal') or next(iter(open_offers), None)
            for name in open_offers:
                if name.lower() in name_hint.lower():
                    target = name
                    break
            return {'action': 'accept', 'investor': target, 'counter_amount': None, 'counter_equity': None}
        # Parse REJECT
        m = re.match(r'REJECT\s+(.*)', line, re.IGNORECASE)
        if m:
            name_hint = m.group(1).strip()
            target = state.get('active_deal') or next(iter(open_offers), None)
            for name in open_offers:
                if name.lower() in name_hint.lower():
                    target = name
                    break
            return {'action': 'reject', 'investor': target, 'counter_amount': None, 'counter_equity': None}
        # Parse COUNTER
        m = re.match(r'COUNTER\s+(.*)', line, re.IGNORECASE)
        if m:
            rest = m.group(1).strip()
            target = state.get('active_deal') or next(iter(open_offers), None)
            for name in open_offers:
                if name.lower() in rest.lower():
                    target = name
                    break
            amt_m = re.search(r'([£$€]?[\d,.]+\s*(?:k|m|million)\b)', rest, re.IGNORECASE)
            eq_m = re.search(r'(\d+(?:\.\d+)?)\s*(?:%|percent)', rest, re.IGNORECASE)
            return {
                'action': 'counter',
                'investor': target,
                'counter_amount': amt_m.group(1).strip() if amt_m else None,
                'counter_equity': eq_m.group(1) + '%' if eq_m else None,
            }
    except Exception:
        pass
    return {'action': 'none'}


def parse_investor_offer(inv_name, raw_resp):
    """
    Parse an investor's response for deal declarations.
    Returns dict with any of: offer, out, joint_proposal, counter_accept, counter_reject
    """
    result = {}

    # OFFER: £200k for 15%
    offer_m = re.search(
        r"\bOFFER:\s*(.+?)(?:\n|$)", raw_resp, re.IGNORECASE
    )
    # Also catch natural offer patterns without the label
    natural_offer = re.search(
        r"(?:i['’]ll|i will|i['’]m offering|i['’]m in for|"
        r"i['’]d do|i['’]d put in|my offer is|i['’]ll do)"
        r"[^.!?]*?([£$€][\d,.]+[km]?|[\d,.]+[km]?\s*(?:pounds|dollars|euros|k|million))"
        r"[^.!?]*?(\d+(?:\.\d+)?)\s*(?:percent|%)",
        raw_resp, re.IGNORECASE
    )

    if offer_m:
        result['offer'] = offer_m.group(1).strip()
    elif natural_offer:
        result['offer'] = natural_offer.group(0).strip()

    # OUT: reason
    out_m = re.search(r"\bI['’]M OUT\b[^.!?]*[.!?]?|\bOUT:\s*(.+?)(?:\n|$)",
                      raw_resp, re.IGNORECASE)
    if out_m:
        result['out'] = (out_m.group(1) or out_m.group(0)).strip()

    # JOINT: propose to another investor
    joint_m = re.search(
        r"(?:partner with|go in with|team up with|split this with)\s+(Alistar|Seraphina|Lucian|Elizabeth)",
        raw_resp, re.IGNORECASE
    )
    if joint_m:
        result['joint_proposal'] = joint_m.group(1).strip()

    # COUNTER_ACCEPT / COUNTER_REJECT
    if re.search(r"\b(deal|you have a deal|i accept|i['’]ll take it)\b",
                 raw_resp, re.IGNORECASE):
        result['counter_accept'] = True
    if re.search(r"\b(no deal|i['’]m out|i['’]ll pass|that['’]s too (low|high|much|little))\b",
                 raw_resp, re.IGNORECASE):
        result['counter_reject'] = True

    return result


def build_deal_signal(state, inv, turn, disp=0):
    """
    Build the deal-aware signal injected into the investor's turn prompt.
    This shapes what the investor should focus on without hardcoding dialogue.
    """
    ask       = state['ask']
    deal_phase = state['deal_phase']
    offers    = state['offers']

    # Phase: exploring — no deal talk yet, minimum turns not met
    if deal_phase == 'exploring':
        if turn < 3:
            return None  # pure business questioning, no deal signal
        # After 3 turns with no ask — gently prompt for it
        if not state['ask_established']:
            return (
                "You have a reasonable sense of the business now. "
                "If you haven't heard what they are looking for from investors today, "
                "it is natural to ask. Or keep probing the business if you need more."
            )
        return None

    # Phase: valuation — ask is known, challenge the numbers
    if deal_phase == 'valuation':
        ask_summary = []
        if ask.get('amount'):   ask_summary.append(ask['amount'])
        if ask.get('equity'):   ask_summary.append(f"for {ask['equity']}")
        if ask.get('valuation'): ask_summary.append(f"implying a {ask['valuation']} valuation")
        ask_str = ' '.join(ask_summary) if ask_summary else 'their ask'
        # Build traction context so investor evaluates ask against what they heard
        traction_hint = ''
        if disp >= 2:
            traction_hint = (
                ' The business fundamentals from this conversation were strong — '
                'factor that into whether these terms are actually attractive.'
            )
        elif disp >= 0:
            traction_hint = ' Consider whether the terms make sense given what you heard.'
        return (
            f"The founder is asking for {ask_str}. "
            "Evaluate this against the traction and moat you just heard about — a low valuation "
            "on a strong business is a good deal, not a red flag. "
            "If the valuation is too high for what you heard, COUNTER at terms you'd actually do: "
            "OFFER: [amount] for [equity%]. "
            "Only use I'M OUT if the business fundamentals are broken."
            f"{traction_hint}"
        )

    # Phase: negotiating — offers are on the table
    if deal_phase == 'negotiating':
        my_offer = offers.get(inv['name'])
        open_offers = {k: v for k, v in offers.items()
                       if v.get('status') == 'open' and k != inv['name']}

        if my_offer and my_offer.get('status') == 'countered':
            counter = my_offer.get('counter', {})
            c_amt = counter.get('amount', '?')
            c_eq  = counter.get('equity', '?')
            return (
                f"The founder countered your offer with {c_amt} for {c_eq}. "
                "You can accept their counter (say 'deal' or 'you have a deal'), "
                "reject it and step out, or come back with a revised offer. "
                "OFFER: [revised terms] if revising. I'M OUT if walking."
            )

        if open_offers:
            competing = ', '.join(
                f"{k} ({v.get('amount','?')} for {v.get('equity','?')})"
                for k, v in open_offers.items()
            )
            if not my_offer:
                return (
                    f"There are already offers on the table from {competing}. "
                    "You can make your own offer, propose a joint deal with another investor, "
                    "or step out if the terms don't work for you. "
                    "OFFER: [amount] for [equity%] to make an offer. "
                    "I'M OUT to step out."
                )

        return (
            "Offers are being discussed. You can make or revise an offer, "
            "propose joining another investor, or step out. "
            "OFFER: [amount] for [equity%] — I'M OUT — or keep the conversation going."
        )

    return None


