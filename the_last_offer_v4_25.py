async def classify_answer(question, answer):
    """
    Classify whether an answer is a business response, a charm attempt, or an insult.
    Returns 'BUSINESS', 'CHARM', or 'INSULT'.
    Uses the 8b model (14,400 req/day) for nuanced tone detection.
    """
    prompt = (
        f"A founder was asked: \"{question}\"\n"
        f"They responded: \"{answer}\"\n\n"
        "Classify this response with exactly one word:\n"
        "BUSINESS — they are attempting to answer the question, even if poorly. "
        "This includes counter-offers, ultimatums, and hard negotiating ("
        "\"7 or I walk\", \"take it or leave it\", \"I need 8%\"). "
        "Tough negotiation is always BUSINESS, never INSULT.\n"
        "CHARM — they are complimenting, flirting with, or flattering the investor "
        "instead of engaging with the substance.\n"
        "INSULT — they are being personally abusive or attacking the investor as a person "
        "(not the deal). Hard bargaining, blunt rejections, and walking threats are NOT insults.\n\n"
        "One word only."
    )
    try:
        resp = await groq_call(
            [{'role': 'user', 'content': prompt}],
            max_tokens=5, temperature=0, model=LIGHT_MODEL
        )
        word = resp.strip().upper()
        for label in ('BUSINESS', 'CHARM', 'INSULT'):
            if label in word:
                return label
    except Exception:
        pass
    return 'BUSINESS'


def score_answer_local(question, answer):
    """
    Score answer quality locally — no API call.
    Returns an int: +2 (impressive) to -2 (complete dodge).
    Parses the SCORE tag from investor response when available;
    this function handles the fallback case from user text alone.
    """
    a = answer.lower().strip()
    words = a.split()
    # Deal language is always neutral-to-positive
    if any(w in a for w in ['deal', 'percent', 'equity', 'offer', 'counter', 'accept', 'valuation']):
        return 0
    if re.search(r'\d', a):
        return 0
    # Obvious non-answers
    if len(words) < 4:
        return -2
    NON_ANSWERS = [
        'i love you', 'i hate you', "i don't know", 'no idea',
        'good question', "that's a great question", 'um', 'uh',
        'pass', 'skip', 'next question', 'i refuse',
    ]
    if any(p in a for p in NON_ANSWERS):
        return -2
    # Longer answers with specific signals
    if len(words) >= 30 and re.search(r'\d', a):
        return 1  # Detailed with numbers
    if len(words) >= 15:
        return 0  # Substantive length
    return 0  # Default neutral


